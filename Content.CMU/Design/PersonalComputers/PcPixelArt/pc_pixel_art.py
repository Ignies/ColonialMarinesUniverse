def tiled(img, box, src, tile_axis):
    """Fills `box` on `img` with `src`, repeated along one axis and cut short at the end, as the window does."""
    x0, y0, x1, y1 = box
    sw, sh = src.size
    if tile_axis == "x":
        x = x0
        while x < x1:
            piece = src.crop((0, 0, min(sw, x1 - x), sh))
            img.alpha_composite(piece, (x, y0))
            x += sw
    else:
        y = y0
        while y < y1:
            piece = src.crop((0, 0, sw, min(sh, y1 - y)))
            img.alpha_composite(piece, (x0, y))
            y += sh


def nine(img, src, box, margins, centre=False):
    l, t, r, b = margins
    sw, sh = src.size
    x0, y0, x1, y1 = box
    cuts = lambda a0, a1, b0, b1: src.crop((a0, b0, a1, b1))  # noqa: E731
    img.alpha_composite(cuts(0, l, 0, t), (x0, y0))
    img.alpha_composite(cuts(sw - r, sw, 0, t), (x1 - r, y0))
    img.alpha_composite(cuts(0, l, sh - b, sh), (x0, y1 - b))
    img.alpha_composite(cuts(sw - r, sw, sh - b, sh), (x1 - r, y1 - b))
    tiled(img, (x0 + l, y0, x1 - r, y0 + t), cuts(l, sw - r, 0, t), "x")
    tiled(img, (x0 + l, y1 - b, x1 - r, y1), cuts(l, sw - r, sh - b, sh), "x")
    tiled(img, (x0, y0 + t, x0 + l, y1 - b), cuts(0, l, t, sh - b), "y")
    tiled(img, (x1 - r, y0 + t, x1, y1 - b), cuts(sw - r, sw, t, sh - b), "y")
    if centre:
        mid = cuts(l, sw - r, t, sh - b).resize((max(1, x1 - x0 - l - r), max(1, y1 - y0 - t - b)), Image.NEAREST)
        img.alpha_composite(mid, (x0 + l, y0 + t))


def bezel(casing, art, glass, w, h, on):
    """The bezel round the screen at `w` x `h` art pixels, put together the way CMUComputerMachine does."""
    frame, plate, pw, ph = art[casing][:4]
    img = Image.new("RGBA", (w, h), (24, 24, 28, 255))
    m = FRAME
    sx0, sy0 = m["left"] - GLASS, m["top"] - GLASS
    sx1, sy1 = w - m["right"] + GLASS, h - m["bottom"] + GLASS
    if on:
        screen = Image.new("RGBA", (sx1 - sx0, sy1 - sy0), (10, 14, 18, 255))
        # A stand-in desktop: a taskbar and a window, in the OS's phosphor.
        phos = {"weyland": (255, 181, 71), "cmb": (143, 196, 255), "upp": (232, 70, 58), "uscm": (156, 191, 110),
                "twe": (226, 179, 60), "iasf": (196, 204, 214), "hyperdyne": (168, 212, 244),
                "prodigy": (238, 240, 244), "kelland": (244, 194, 26), "lasalle": (79, 216, 176)}.get(
            casing, (63, 224, 90))
        for y in range(0, screen.height, 3):
            for x in range(screen.width):
                screen.putpixel((x, y), (6, 9, 12, 255))
        for x in range(screen.width):
            screen.putpixel((x, screen.height - 8), phos + (255,))
        for x in range(12, 60):
            screen.putpixel((x, 12), phos + (255,))
            screen.putpixel((x, 40), phos + (255,))
        img.alpha_composite(screen, (sx0, sy0))
    else:
        img.alpha_composite(Image.new("RGBA", (sx1 - sx0, sy1 - sy0), (0, 0, 0, 255)), (sx0, sy0))
        g = glass.image((0, 0, 2 * GLASS_OFF + 4, 2 * GLASS_OFF + 4))
        nine(img, g, (sx0, sy0, sx1, sy1), (GLASS_OFF,) * 4, centre=True)
    nine(img, frame.image((0, 0, FRAME_W, FRAME_H)), (0, 0, w, h), (m["left"], m["top"], m["right"], m["bottom"]))
    img.alpha_composite(plate.image((0, 0, pw, ph)), ((w - pw) // 2, PLATE_Y))
    return img


def panel(casing, art, w, on, card):
    """The front panel at `w` art pixels wide, with the lights and power key as the window shows them."""
    fascia, housing = art[casing][4:]
    top = -LAYOUT["card"][1]
    img = Image.new("RGBA", (w, FASCIA_H + top), (0, 0, 0, 0))
    fa = fascia.image((0, 0, FASCIA_W, FASCIA_H))
    img.alpha_composite(fa.crop((0, 0, FASCIA_LEFT, FASCIA_H)), (0, top))
    tiled(img, (FASCIA_LEFT, top, w - FASCIA_RIGHT, top + FASCIA_H),
          fa.crop((FASCIA_LEFT, 0, FASCIA_LEFT + TILE, FASCIA_H)), "x")
    img.alpha_composite(fa.crop((FASCIA_W - FASCIA_RIGHT, 0, FASCIA_W, FASCIA_H)), (w - FASCIA_RIGHT, top))
    rx = w - FASCIA_RIGHT
    hx, hy, hw, hh = LAYOUT["housing"]
    img.alpha_composite(housing.image((0, 0, hw, hh)), (rx + hx, top + hy))
    rdx, rdy = rx + LAYOUT["reader"][0] - 145, top + LAYOUT["reader"][1] - 100
    over = Canvas()
    if on:
        over.paste(moved(atm.led("led_power", "green"), rx + LAYOUT["led_power"][0] - 31, top + LAYOUT["led_power"][1] - 196))
        over.paste(moved(atm.led("led_power", "amber"), LAYOUT["led_disk"][0] - 31, top + LAYOUT["led_disk"][1] - 196))
        over.paste(moved(atm.rails("#7dffa0", "#46ff7740"), rdx, rdy))
    if card:
        over.paste(moved(atm.seated(1), rdx, rdy))
    img.alpha_composite(over.image((0, 0, w, FASCIA_H + top)))
    bx, by, bw, bh = LAYOUT["power"]
    img.alpha_composite(draw_power(casing, on, "").image((0, 0, bw, bh)), (rx + bx, top + by))
    return img, top


def machine(casing, art, glass, width, height, on, card=False):
    """The whole machine at `width` x `height` screen pixels: the bezel at FRAME_ZOOM, the panel at FASCIA_ZOOM."""
    ph = FASCIA_H * FASCIA_ZOOM
    top = bezel(casing, art, glass, width // FRAME_ZOOM, (height - ph) // FRAME_ZOOM, on)
    bottom, rise = panel(casing, art, width // FASCIA_ZOOM, on, card)
    img = Image.new("RGBA", (width, height), (24, 24, 28, 255))
    img.alpha_composite(top.resize((top.width * FRAME_ZOOM, top.height * FRAME_ZOOM), Image.NEAREST))
    img.alpha_composite(bottom.resize((bottom.width * FASCIA_ZOOM, bottom.height * FASCIA_ZOOM), Image.NEAREST),
                        (0, height - ph - rise * FASCIA_ZOOM))
    return img


def export_review(art, glass, power):
    REVIEW.mkdir(exist_ok=True)
    for old in REVIEW.glob("*.png"):
        old.unlink()
    shots = []
    for casing in CASINGS:
        # The window's smallest machine and its default one, in screen pixels.
        for w, h, on, card in ((618, 534, False, True), (876, 714, True, True)):
            img = machine(casing, art, glass, w, h, on, card)
            img.save(REVIEW / f"machine_{casing}_{w}x{h}_{'on' if on else 'off'}.png")
            shots.append(img)

    # Contact sheet: every texture and the button states, at 3x, on a neutral ground.
    pieces = []
    for casing in CASINGS:
        frame, plate, pw, ph, fascia, housing = art[casing]
        pieces.append([frame.image((0, 0, FRAME_W, FRAME_H)), plate.image((0, 0, pw, ph)),
                       housing.image((0, 0) + HOUSING_SRC[2:])])
        pieces.append([fascia.image((0, 0, FASCIA_W, FASCIA_H))])
        pieces.append([layer.image((0, 0) + LAYOUT["power"][2:]) for name, layer in power if name.startswith(casing)])
    n = 2 * GLASS_OFF + 4
    pieces.append([glass.image((0, 0, n, n))])
    gap = 6
    rows = [(max(p.height for p in row), sum(p.width for p in row) + gap * (len(row) - 1)) for row in pieces]
    sheet = Image.new("RGBA", (max(r[1] for r in rows) + 2 * gap, sum(r[0] for r in rows) + gap * (len(rows) + 1)),
                      (54, 56, 60, 255))
    y = gap
    for row, (rh, _) in zip(pieces, rows):
        x = gap
        for p in row:
            sheet.alpha_composite(p, (x, y))
            x += p.width + gap
        y += rh + gap
    sheet = sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST)
    sheet.save(REVIEW / "contact_sheet.png")
    return sheet


