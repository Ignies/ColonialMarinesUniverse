def lightness(c):
    return 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]


def on_ramp(ramp, v):
    for (v0, c0), (v1, c1) in zip(ramp, ramp[1:]):
        if v <= v1:
            t = (v - v0) / (v1 - v0) if v1 > v0 else 0
            a, b = rgba(c0), rgba(c1)
            return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))
    return rgba(ramp[-1][1])[:3]


def vivid(c):
    hi, lo = max(c[:3]), min(c[:3])
    return hi > 90 and (hi - lo) / hi > 0.5


def recolour(layer, casing):
    if casing == "seegson":
        return layer
    ramp = RAMPS[casing]
    for k, c in list(layer.px.items()):
        if not vivid(c):
            layer.px[k] = on_ramp(ramp, lightness(c)) + (c[3],)
    return layer


