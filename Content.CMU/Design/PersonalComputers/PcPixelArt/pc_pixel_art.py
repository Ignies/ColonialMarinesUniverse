def draw_glass_off():
    """
    A dead tube, as the ATM's glass is drawn: darkening towards the bezel in steps, a gleam across its top left and a
    fainter one in the bottom right, where the room's light catches the curve.
    """
    n = 2 * GLASS_OFF + 4
    ramp = ("#050706", "#090c0a", "#0c100d", "#0f1410", "#121813")
    steps = (1, 3, 6, 10)
    L = Canvas("glass_off")
    for y in range(n):
        for x in range(n):
            dx, dy = min(x, n - 1 - x), min(y, n - 1 - y)
            d = min(dx, dy, (dx + dy) // 2 + 1)
            L.set(x, y, ramp[next((i for i, s in enumerate(steps) if d < s), len(steps))])
    # The window's reflection: a broad streak with a thin one beside it, brightest in the middle of its run.
    for i in range(17):
        hot = 4 <= i <= 12
        for j in range(3):
            L.set(2 + i + j, 18 - i + j, "#2c3830" if hot and j == 1 else "#222b25")
    for i in range(2, 10):
        L.set(2 + i, 21 - i + 2, "#1b221d")
    for i in range(9):
        L.set(n - 5 - i, n - 14 + i, "#1b221d")
        L.set(n - 6 - i, n - 14 + i, "#171d19")
    return L


