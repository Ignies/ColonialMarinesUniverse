# The ATM's key cap colours for each look: plain is its lit key, hover and pressed its own.
POWER_FACES = {"": "on", "_hover": "hover", "_pressed": "pressed"}


def draw_power(casing, on, look):
    """
    The power key: the ATM's key cap, square, with the power mark pressed into it. While the machine runs the mark is
    lit green from behind, its light spilling a pixel round it.
    """
    face, hi, lhi, lo, rlo, _, _ = atm.KEY_STATES[POWER_FACES[look]]
    _, _, w, h = LAYOUT["power"]
    sunk = look == "_pressed"
    L = Canvas("power")
    L.outline(0, 0, w - 1, h - 1, C["key_ol"], rounded=True)
    L.rect(1, 1, w - 2, h - 2, face)
    if sunk:
        L.rect(1, 1, w - 2, 2, hi)
        L.rect(1, h - 2, w - 2, h - 2, lo)
    else:
        L.rect(1, 1, w - 2, 1, hi)
        L.rect(1, 2, 1, h - 4, lhi)
        L.rect(1, h - 3, w - 2, h - 2, lo)
        L.rect(w - 2, 2, w - 2, h - 3, rlo)
    ox, oy = (w - len(POWER_ICON[0])) // 2, (h - len(POWER_ICON)) // 2 - 1 + (1 if sunk else 0)
    mark = Canvas()
    for y, row in enumerate(POWER_ICON):
        for x, bit in enumerate(row):
            if bit == "#":
                mark.set(ox + x, oy + y, "#7dffa0")
    if not on:
        # Pressed into the cap: dark strokes, their lower edge catching the light.
        for (x, y) in mark.px:
            L.set(x, y + 1, "#a08a68")
        for (x, y) in mark.px:
            L.set(x, y, "#3d2f1f")
        return recolour(L, casing)
    recolour(L, casing)
    glow = Canvas()
    for (x, y) in mark.px:
        for ddx, ddy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            if (x + ddx, y + ddy) not in mark.px:
                glow.set(x + ddx, y + ddy, "#46ff7768" if look != "_hover" else "#46ff7790")
    L.blend(glow)
    L.paste(mark)
    L.set(ox + 4, oy, "#c8ffd8")
    return L


