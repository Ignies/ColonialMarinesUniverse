class Canvas(atm.Layer):
    """The ATM's layer without its 227x300 bounds, so a slice can be any size."""

    def set(self, x, y, c):
        self.px[(x, y)] = rgba(c)

    def unset(self, x, y):
        self.px.pop((x, y), None)


def moved(layer, dx, dy):
    out = Canvas()
    for (x, y), c in layer.px.items():
        out.px[(x + dx, y + dy)] = c
    return out


