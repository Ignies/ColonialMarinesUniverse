SIZE = 24

INK = (22, 24, 40, 255)

# Ramps: light, base, shade.
SUN = ((255, 248, 170, 255), (255, 214, 60, 255), (236, 140, 30, 255))
MOON = ((255, 252, 230, 255), (232, 226, 190, 255), (178, 170, 140, 255))
CLOUD = ((255, 255, 255, 255), (220, 228, 240, 255), (168, 180, 202, 255))
GREY = ((196, 202, 214, 255), (150, 158, 176, 255), (110, 116, 136, 255))
DARK = ((132, 136, 156, 255), (92, 96, 118, 255), (64, 66, 86, 255))
RAIN = ((150, 210, 255, 255), (70, 150, 240, 255))
BOLT = ((255, 250, 190, 255), (255, 214, 40, 255))
SNOW = ((255, 255, 255, 255), (200, 228, 255, 255))
FOG = ((226, 230, 236, 255), (188, 194, 206, 255))
WIND = ((236, 248, 255, 255), (160, 210, 240, 255))
DUST = ((234, 196, 140, 255), (200, 150, 92, 255), (150, 104, 60, 255))


class Canvas:
    """A 24x24 RGBA pixel grid with shapes tested at pixel centres, and an outline pass."""

    def __init__(self):
        self.px = [[None] * SIZE for _ in range(SIZE)]

    def set(self, x, y, c):
        if 0 <= x < SIZE and 0 <= y < SIZE:
            self.px[y][x] = c

    def get(self, x, y):
        if 0 <= x < SIZE and 0 <= y < SIZE:
            return self.px[y][x]
        return None

    def fill(self, inside, colour):
        """Sets every pixel whose centre passes inside(cx, cy); colour may be a function of (x, y)."""
        for y in range(SIZE):
            for x in range(SIZE):
                if inside(x + 0.5, y + 0.5):
                    self.set(x, y, colour(x, y) if callable(colour) else colour)

    def disc(self, cx, cy, r, colour):
        self.fill(lambda x, y: (x - cx) ** 2 + (y - cy) ** 2 <= r * r, colour)

    def rect(self, x0, y0, x1, y1, colour):
        self.fill(lambda x, y: x0 <= x < x1 and y0 <= y < y1, colour)

    def poly(self, pts, colour):
        def inside(x, y):
            hit = False
            for i in range(len(pts)):
                ax, ay = pts[i]
                bx, by = pts[(i + 1) % len(pts)]
                if (ay <= y) != (by <= y) and x < ax + (y - ay) / (by - ay) * (bx - ax):
                    hit = not hit
            return hit
        self.fill(inside, colour)

    def line(self, x0, y0, x1, y1, colour):
        """A one pixel Bresenham line between pixel coordinates."""
        dx, dy = abs(x1 - x0), -abs(y1 - y0)
        sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
        err = dx + dy
        while True:
            self.set(x0, y0, colour)
            if x0 == x1 and y0 == y1:
                return
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy

    def outline(self, colour=INK):
        """Rings every opaque area: each empty pixel touching an opaque one (4 ways) becomes colour."""
        ring = [(x, y) for y in range(SIZE) for x in range(SIZE) if self.px[y][x] is None
                and any(self.get(x + dx, y + dy) not in (None, colour) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))]
        for x, y in ring:
            self.set(x, y, colour)

    def image(self):
        img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
        for y in range(SIZE):
            for x in range(SIZE):
                if self.px[y][x]:
                    img.putpixel((x, y), self.px[y][x])
        return img


def shaded(ramp, cx, cy, r):
    """A colour function lighting a round shape from the top-left: light rim, base, shade to the bottom-right."""
    light, base, shade = ramp

    def colour(x, y):
        dx, dy = (x + 0.5 - cx) / r, (y + 0.5 - cy) / r
        k = dx * 0.6 + dy * 0.8
        if k < -0.45:
            return light
        if k > 0.35:
            return shade
        return base
    return colour


def cloud(c, ramp, ox=0, oy=0, scale=1.0):
    """A heaped cloud: three puffs on a flat base, lit from the top-left, with a shaded underside."""
    light, base, shade = ramp
    puffs = [(7.5, 13.5, 4.2), (12.5, 10.0, 5.6), (17.5, 13.0, 4.4)]
    puffs = [(ox + 12 + (x - 12) * scale, oy + 12 + (y - 12) * scale, r * scale) for x, y, r in puffs]
    bottom = oy + 12 + (17.5 - 12) * scale
    left = ox + 12 + (4 - 12) * scale
    right = ox + 12 + (21 - 12) * scale

    def inside(x, y):
        if left <= x <= right and puffs[0][1] <= y <= bottom:
            return True
        return any((x - px) ** 2 + (y - py) ** 2 <= r * r for px, py, r in puffs)

    def colour(x, y):
        cx, cy = x + 0.5, y + 0.5
        if cy > bottom - 2.2 * scale:
            return shade
        for px, py, r in puffs:
            d = math.hypot(cx - (px - r * 0.3), cy - (py - r * 0.35))
            if d < r * 0.55:
                return light
        return base
    c.fill(inside, colour)
    return bottom


def sun():
    c = Canvas()
    for k in range(8):
        a = k * math.pi / 4
        tip = (12 + math.cos(a) * 11.2, 12 + math.sin(a) * 11.2)
        side = 1.9
        b1 = (12 + math.cos(a) * 7.5 - math.sin(a) * side, 12 + math.sin(a) * 7.5 + math.cos(a) * side)
        b2 = (12 + math.cos(a) * 7.5 + math.sin(a) * side, 12 + math.sin(a) * 7.5 - math.cos(a) * side)
        c.poly([tip, b1, b2], SUN[1] if k % 2 else SUN[2])
    c.disc(12, 12, 6.6, shaded(SUN, 12, 12, 6.6))
    c.set(9, 9, (255, 255, 255, 255))
    c.set(10, 9, SUN[0])
    c.set(9, 10, SUN[0])
    c.outline()
    return c


def night():
    c = Canvas()
    cx, cy, r = 11, 12.5, 8.2
    c.fill(lambda x, y: (x - cx) ** 2 + (y - cy) ** 2 <= r * r and (x - (cx + 4.6)) ** 2 + (y - (cy - 3.4)) ** 2 > (r * 0.86) ** 2,
           shaded(MOON, cx, cy, r))
    for x, y in ((6, 13), (8, 18), (5, 10)):
        if c.get(x, y):
            c.set(x, y, MOON[2])
    c.outline()
    for sx, sy, big in ((19, 15, True), (17, 5, False)):
        c.set(sx, sy, (255, 255, 255, 255))
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            c.set(sx + dx, sy + dy, (255, 240, 170, 255))
        if big:
            for dx, dy in ((2, 0), (-2, 0), (0, 2), (0, -2)):
                c.set(sx + dx, sy + dy, (200, 190, 140, 255))
    return c


def plain_cloud():
    c = Canvas()
    cloud(c, CLOUD, 0, 1)
    c.outline()
    return c


def rain():
    c = Canvas()
    bottom = cloud(c, GREY, 0, -3)
    for x0 in (7, 11, 15, 19):
        for k, (dx, dy) in enumerate(((0, 0), (-1, 1), (-1, 2), (-2, 3))):
            c.set(x0 + dx - 1, int(bottom) + 2 + dy, RAIN[0] if k == 0 else RAIN[1])
        for k, (dx, dy) in enumerate(((0, 0), (-1, 1))):
            c.set(x0 + dx - 3, int(bottom) + 7 + dy, RAIN[1])
    c.outline()
    return c


def storm():
    c = Canvas()
    cloud(c, DARK, 0, -4)
    c.poly([(13.5, 11), (9, 18), (12, 18), (10, 23.5), (16.5, 15), (13, 15), (15.5, 11)], lambda x, y: BOLT[0] if x < 12 else BOLT[1])
    for x0, y0 in ((6, 17), (19, 17)):
        c.set(x0, y0, RAIN[1])
        c.set(x0 - 1, y0 + 1, RAIN[1])
    c.outline()
    return c


def snow():
    c = Canvas()
    bottom = int(cloud(c, CLOUD, 0, -4))
    c.outline()
    for fx, fy in ((7, bottom + 4), (12, bottom + 6), (17, bottom + 3)):
        for dx, dy in ((0, 0), (1, 0), (-1, 0), (0, 1), (0, -1)):
            c.set(fx + dx, fy + dy, SNOW[0])
        for dx, dy in ((1, 1), (-1, -1), (1, -1), (-1, 1)):
            c.set(fx + dx, fy + dy, SNOW[1])
        for dx, dy in ((2, 0), (-2, 0), (0, 2), (0, -2), (2, 1), (2, -1), (-2, 1), (-2, -1), (1, 2), (-1, 2), (1, -2), (-1, -2)):
            if c.get(fx + dx, fy + dy) is None:
                c.set(fx + dx, fy + dy, INK)
    return c


def fog():
    c = Canvas()
    bands = ((5, 3, 19), (10, 1, 21), (15, 4, 22), (20, 2, 16))
    for i, (y, x0, x1) in enumerate(bands):
        def inside(x, yy, y=y, x0=x0, x1=x1, i=i):
            wave = math.sin(x * 0.4 + i * 1.7) * 0.6
            return x0 <= x <= x1 and abs(yy - (y + wave)) <= 1.5

        c.fill(inside, lambda x, yy, y=y: FOG[0] if yy < y else FOG[1])
    c.outline()
    return c


def wind():
    c = Canvas()
    gusts = ((6, 2, 12, 2.4), (13, 1, 18, 3.0), (19, 4, 14, 0))
    for y, x0, x1, r in gusts:
        # The gust: a two pixel stroke, light on top.
        for x in range(x0, x1 + 1):
            c.set(x, y, WIND[0])
            c.set(x, y + 1, WIND[1])
        # The curl: from the end of the stroke round the right and over the top, back towards the start.
        if not r:
            continue
        cx, cy = x1, y + 0.5 - r
        for k in range(60):
            a = math.pi / 2 - k * (math.pi * 1.45 / 59)
            for rr, col in ((r + 0.5, WIND[1]), (r - 0.5, WIND[0])):
                c.set(round(cx + math.cos(a) * rr), round(cy + math.sin(a) * rr), col)
    c.outline()
    return c


def dust():
    c = Canvas()
    light, base, shade = DUST
    # Streaks of blown grit trailing off to the left.
    for y, x0, x1 in ((8, 1, 9), (14, 0, 6), (20, 2, 10)):
        for x in range(x0, x1 + 1):
            c.set(x, y, light if x > x0 + 2 else base)
            c.set(x, y + 1, base if x > x0 + 2 else shade)
    puffs = ((15, 11.5, 5.2), (19, 15.5, 4.2), (12, 16, 4.6), (16.5, 18.5, 3.6))

    def inside(x, y):
        return any((x - px) ** 2 + (y - py) ** 2 <= r * r for px, py, r in puffs)

    def colour(x, y):
        cx, cy = x + 0.5, y + 0.5
        for px, py, r in puffs:
            if math.hypot(cx - (px - r * 0.35), cy - (py - r * 0.4)) < r * 0.5:
                return light
        return shade if cy > 19 or (cx > 19.5 and cy > 15) else base
    c.fill(inside, colour)
    c.outline()
    for gx, gy in ((3, 4), (7, 12), (2, 17), (8, 23), (22, 6), (5, 22)):
        c.set(gx, gy, shade)
    return c


ICONS = {"sun": sun, "night": night, "cloud": plain_cloud, "rain": rain, "storm": storm, "snow": snow, "fog": fog,
         "wind": wind, "dust": dust}


def attributions(names):
    lines = []
    lines.append('- files: [' + ", ".join(f'"{n}.png"' for n in names) + ']')
    lines.append(f'  license: "{LICENSE}"')
    lines.append(f'  copyright: "{COPYRIGHT}"')
    lines.append('  source: "https://github.com/Ignies/ColonialMarinesUniverse"')
    lines.append("")
    return "\n".join(lines)


def main():
    TEXTURES.mkdir(parents=True, exist_ok=True)
    REVIEW.mkdir(parents=True, exist_ok=True)
    images = {}
    for name, draw in ICONS.items():
        img = draw().image()
        img.save(TEXTURES / f"{name}.png")
        images[name] = img
        print(f"{name}.png")
    with open(TEXTURES / "attributions.yml", "w", encoding="utf-8", newline="\n") as f:
        f.write(attributions(list(ICONS)))
    sheet = Image.new("RGBA", (len(images) * (SIZE * 4 + 8) + 8, SIZE * 4 + 16), (40, 40, 44, 255))
    for i, img in enumerate(images.values()):
        big = img.resize((SIZE * 4, SIZE * 4), Image.NEAREST)
        sheet.alpha_composite(big, (8 + i * (SIZE * 4 + 8), 8))
    sheet.save(REVIEW / "weather_icons.png")
    print(f"{len(images)} icons into {TEXTURES}, sheet at {REVIEW / 'weather_icons.png'}")


if __name__ == "__main__":
    main()
