"""
Pixel-art weather icons for YouTape's weather reports: the symbols a presenter stands beside on the weather map.

Run from anywhere:  python youtape_weather_icons.py

Writes the game assets into Content.CMU/Resources/Textures/CMU14/PersonalComputers/Sites/Retro/YouTape/Weather/,
with their attributions.yml, and a 4x contact sheet of every icon on dark grey into youtape_weather/ in the system
temp folder, outside the repo.

Every icon is 24x24 with a transparent background, drawn at 1x the way the late-80s weather graphics were: flat
colour shapes, a lit top-left and a shaded bottom-right step, and one dark outline round the whole symbol so it
reads on any map colour. Shapes are drawn into a Canvas (discs, polygons, lines, all tested at pixel centres so
nothing is anti-aliased); outline() then rings every opaque area in INK. The game shows the icons at 2x.

  sun    a disc with eight rays          night  a crescent moon with two stars
  cloud  a heaped cumulus               rain   a grey cloud with slanting drops
  storm  a dark cloud with a bolt       snow   a cloud with snowflakes
  fog    banks of drifting mist         wind   three curling gusts
  dust   a rolling dust cloud trailing streaks of grit
"""
