# A modern handheld TPV in Weyland-Yutani colours: a charcoal slab, the gold printer-roll head on top
# with the paper slit along its edge, a CRT-style screen and the keypad under it.
def wy_logo(L, x0, y0, h, w, m, gold, hi, cut):
    """The geometric W-Y mark: four 45-degree strokes and three notches."""
    b0 = x0 + 2 * (h - 1)
    d0 = b0 + 2 * (h - 1)
    for y in range(h):
        for xs in (x0 + y, b0 - y, b0 + y, d0 - y):
            L.rect(xs, y0 + y, xs + w - 1, y0 + y, gold if y else hi)
        for left, right in ((x0 + y + w + m, b0 - y - 1 - m), (b0 + y + w + m, d0 - y - 1 - m),
                            (b0 - y + w + m, b0 + y - 1 - m)):
            if left <= right:
                L.rect(left, y0 + y, right, y0 + y, cut)


def draw_body():
    L = Layer()
    x, y, w, h = LAYOUT["body"]
    x1, y1 = x + w - 1, y + h - 1
    rounded(L, x, y, x1, y1, 8, C["outline"])
    rounded(L, x + 1, y + 1, x1 - 1, y1 - 1, 7, C["body_hi"])
    rounded(L, x + 2, y + 2, x1 - 1, y1 - 1, 7, C["body_lo"])
    rounded(L, x + 2, y + 2, x1 - 2, y1 - 2, 6, C["body"])

    # The printer-roll head: gold, lit along its rounded top, a dark seam where it meets the body.
    _, hy, _, hh = LAYOUT["head"]
    head = Layer()
    rounded(head, x + 1, hy + 1, x1 - 1, hy + hh + 6, 7, C["gold"])
    for (px, py), _ in list(head.px.items()):
        if py <= hy + hh:
            depth = py - hy
            colour = C["gold_hi"] if depth <= 2 else C["gold"] if depth < hh - 4 else C["gold_lo"]
            L.set(px, py, colour)
    L.rect(x + 1, hy + hh, x1 - 1, hy + hh, C["outline"])
    L.rect(x + 2, hy + hh + 1, x1 - 2, hy + hh + 1, C["body_lo"])

    sx, sy, sw, sh = LAYOUT["slit"]
    L.rect(sx, sy, sx + sw - 1, sy + sh - 1, C["slot"])
    for i in range(sx, sx + sw, 2):
        L.set(i, sy + sh, C["gold_lo"])

    lx, ly, lw, lh = LAYOUT["logo"]
    wy_logo(L, lx, ly, lh, 3, 1, C["gold_ink"], C["gold_lo"], C["gold"])
    L.paste(pad_symbol(C["gold_ink"]))
    L.paste(lights(0))

    # A CRT in a thick bezel: rounded corners, a lit lip above and a deep shadow inside.
    bx, by, bw, bh = LAYOUT["bezel"]
    rounded(L, bx, by, bx + bw - 1, by + bh - 1, 7, C["bezel"])
    rounded(L, bx + 1, by + 1, bx + bw - 2, by + 3, 6, C["bezel_hi"])
    rounded(L, bx + 2, by + 3, bx + bw - 3, by + bh - 3, 6, C["bezel"])
    gx, gy, gw, gh = LAYOUT["glass"]
    rounded(L, gx - 1, gy - 1, gx + gw, gy + gh, 6, "#050606")

    brand = "WEYLAND-YUTANI"
    L.glyphs(F3, (W - text_width(F3, brand)) // 2, by + bh + 3, brand, "#5d6268")

    for i in range(len(KEYPAD)):
        kx, ky, _, _ = key_rect(i)
        L.rect(kx + 1, ky + KEY_H, kx + KEY_W - 2, ky + KEY_H, "#121315")
        draw_key(L, i, "on")
    return L


def pad_symbol(colour):
    """The contactless mark on the head: a card beside four widening waves."""
    L = Layer()
    ax, ay, aw, ah = LAYOUT["pad"]
    cx, cy = ax + aw // 2, ay + ah // 2
    L.rect(cx - 12, cy - 3, cx - 5, cy + 3, colour)
    L.rect(cx - 11, cy - 2, cx - 6, cy + 2, C["gold"])
    L.rect(cx - 11, cy - 1, cx - 6, cy - 1, colour)
    for i in range(4):
        half = 1 + i
        x = cx - 1 + i * 3
        for dy in range(-half, half + 1):
            L.set(x + (1 if abs(dy) < half else 0), cy + dy, colour)
    return L


