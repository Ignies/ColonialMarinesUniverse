def write_rsi(path, size, states):
    path.mkdir(parents=True, exist_ok=True)
    for old in path.glob("*.png"):
        old.unlink()
    meta = {"version": 1, "license": LICENSE, "copyright": COPYRIGHT,
            "size": {"x": size[0], "y": size[1]}, "states": []}
    for state in states:
        name, frames, delays = state[:3]
        directions = state[3] if len(state) > 3 else 1
        if isinstance(frames, Image.Image):
            frames.save(path / f"{name}.png")
        else:
            sheet = Image.new("RGBA", (size[0] * len(frames), size[1]), (0, 0, 0, 0))
            for i, frame in enumerate(frames):
                sheet.paste(frame, (i * size[0], 0))
            sheet.save(path / f"{name}.png")
        entry = {"name": name}
        if directions > 1:
            entry["directions"] = directions
        if delays:
            entry["delays"] = [delays]
        meta["states"].append(entry)
    (path / "meta.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8", newline="\n")


def crop(layer, rect):
    return layer.image(rect)


