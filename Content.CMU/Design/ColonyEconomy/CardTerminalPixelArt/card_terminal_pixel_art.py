def rgba(c):
    if isinstance(c, tuple):
        return c
    c = c.lstrip("#")
    return int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16), int(c[6:8], 16) if len(c) == 8 else 255


def shade(colour, keep):
    r, g, b, a = rgba(colour)
    return min(255, int(r * keep)), min(255, int(g * keep)), min(255, int(b * keep)), a


class Layer:
    def __init__(self, w=W, h=H):
        self.w, self.h = w, h
        self.px = {}

    def set(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.px[(x, y)] = rgba(c)

    def rect(self, x0, y0, x1, y1, c):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.set(x, y, c)

    def glyphs(self, font, x, y, text, c, gap=1):
        for ch in text:
            g = font.get(ch, font.get(" ", [".."]))
            for gy, row in enumerate(g):
                for gx, bit in enumerate(row):
                    if bit == "#":
                        self.set(x + gx, y + gy, c)
            x += len(g[0]) + gap

    def bitmap(self, rows, x, y, c):
        for gy, row in enumerate(rows):
            for gx, bit in enumerate(row):
                if bit == "#":
                    self.set(x + gx, y + gy, c)

    def paste(self, other):
        self.px.update(other.px)

    def image(self, rect=None):
        x0, y0, w, h = rect or (0, 0, self.w, self.h)
        img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        for (x, y), c in self.px.items():
            if x0 <= x < x0 + w and y0 <= y < y0 + h:
                img.putpixel((x - x0, y - y0), c)
        return img


def text_width(font, text, gap=1):
    return sum(len(font.get(ch, font.get(" ", [".."]))[0]) + gap for ch in text) - gap


def bevel(L, x0, y0, x1, y1, hi, lo, raised=True):
    top, bottom = (hi, lo) if raised else (lo, hi)
    L.rect(x0, y0, x1, y0, top)
    L.rect(x0, y0, x0, y1, top)
    L.rect(x0, y1, x1, y1, bottom)
    L.rect(x1, y0, x1, y1, bottom)


def rounded(L, x0, y0, x1, y1, r, c):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            dx = max(x0 + r - x, 0, x - (x1 - r))
            dy = max(y0 + r - y, 0, y - (y1 - r))
            if dx * dx + dy * dy <= r * r:
                L.set(x, y, c)


