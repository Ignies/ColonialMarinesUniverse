def key_rect(index):
    _, col, row = KEYPAD[index]
    return KEY_X + col * PITCH_X, KEY_Y + row * PITCH_Y, KEY_W, KEY_H


def draw_key(L, index, state):
    label = KEYPAD[index][0]
    face, hi, lo, legend = KEY_FACES.get(label, KEY_FACES["digit"])
    if state == "off":
        face, hi, legend = shade(face, 0.7), shade(hi, 0.7), shade(legend, 0.45)
    elif state == "hover":
        face, hi = shade(face, 1.18), shade(hi, 1.15)
    x, y, w, h = key_rect(index)
    sunk = state == "pressed"
    L.rect(x, y, x + w - 1, y + h - 1, C["outline"])
    L.rect(x + 1, y + 1, x + w - 2, y + h - 2, face)
    if sunk:
        L.rect(x + 1, y + 1, x + w - 2, y + 1, lo)
    else:
        L.rect(x + 1, y + 1, x + w - 2, y + 1, hi)
        L.rect(x + 1, y + h - 2, x + w - 2, y + h - 2, lo)
    top = y + 2 + (1 if sunk else 0)
    if label == "clear":
        L.bitmap(CLEAR_ICON, x + (w - len(CLEAR_ICON[0])) // 2, top + 1, legend)
    elif label == "menu":
        L.glyphs(F3, x + (w - text_width(F3, "MENU")) // 2, top + 1, "MENU", legend)
    else:
        text = {"cancel": "X", "enter": "OK"}.get(label, label)
        L.glyphs(F5, x + (w - text_width(F5, text)) // 2, top, text, legend)


def key_layer(index, state):
    L = Layer()
    draw_key(L, index, state)
    x, y, _, _ = key_rect(index)
    out = Layer()
    for (px, py), c in L.px.items():
        out.set(px - x + KEY_X, py - y + KEY_Y, c)
    return out


