def screen(level):
    """CRT glass: rounded corners, darker toward the edges, a soft glare at the top left."""
    L = Layer()
    x, y, w, h = LAYOUT["glass"]
    ramp = [shade(c, level) for c in ("#030805", "#050c07", "#07110a", "#09150c", "#0b180e")]
    mask = Layer()
    rounded(mask, x, y, x + w - 1, y + h - 1, 6, "#ffffff")
    for (xx, yy) in mask.px:
        d = min(xx - x, x + w - 1 - xx, yy - y, y + h - 1 - yy)
        L.set(xx, yy, ramp[min(d // 3, 4)])
    for i in range(18):
        L.set(x + 4 + i, y + 4, shade("#1a2f20", level))
        if i < 10:
            L.set(x + 4, y + 5 + i // 2, shade("#14261a", level))
    return L


def lights(lit, colour="#46ff77"):
    L = Layer()
    lx, ly, _, _ = LAYOUT["lights"]
    for i in range(4):
        x = lx + i * 6
        if i < lit:
            L.rect(x, ly, x + 4, ly + 4, shade(colour, 0.6))
            L.rect(x + 1, ly + 1, x + 3, ly + 3, colour)
            L.set(x + 1, ly + 1, "#e8fff0" if colour == "#46ff77" else "#ffe8e8")
        else:
            L.rect(x, ly, x + 4, ly + 4, C["gold_lo"])
            L.rect(x + 1, ly + 1, x + 3, ly + 3, C["led_off"])
    return L


# ── Receipt ──────────────────────────────────────────────────────────────────
# Out of the slit and away up the top of the device: narrowing as it recedes, dark where it is
# still in the slit, leading edge first, printed lines across it.
RECEIPT_ROWS = 24
RECEIPT_NEAR_W, RECEIPT_FAR_W = 62, 52
RECEIPT_SHADE = (0.8, 0.55, 0.35, 0.2, 0.1)
PAPER = dict(edge="#8d877a", paper="#ece8dc", ink="#8d877a")
PRINT_DELAYS = [0.15, 0.17, 0.17, 0.17, 0.17, 0.17, 0.25]


def receipt_span(row):
    width = RECEIPT_NEAR_W + (RECEIPT_FAR_W - RECEIPT_NEAR_W) * row / (RECEIPT_ROWS - 1)
    mid = LAYOUT["slit"][0] + LAYOUT["slit"][2] / 2
    return round(mid - width / 2), round(mid + width / 2) - 1


def receipt(out):
    L = Layer()
    out = min(out, RECEIPT_ROWS)
    base = LAYOUT["slit"][1] + 1
    for row in range(out):
        x0, x1 = receipt_span(row)
        v = 1 - (out - row - 0.5) / RECEIPT_ROWS
        printed = 0.15 < v < 0.9 and int(v * RECEIPT_ROWS) % 3 == 0
        y = base - row
        for x in range(x0, x1 + 1):
            u = (x - x0 + 0.5) / (x1 - x0 + 1)
            if x in (x0, x1) or row == out - 1:
                c = PAPER["edge"]
            elif printed and 0.12 < u < (0.88 if int(v * RECEIPT_ROWS) % 2 else 0.6):
                c = PAPER["ink"]
            else:
                c = PAPER["paper"]
            L.set(x, y, shade(c, 1 - (RECEIPT_SHADE[row] if row < len(RECEIPT_SHADE) else 0)))
    return L


