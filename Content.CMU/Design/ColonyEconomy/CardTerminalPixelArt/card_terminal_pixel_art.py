def mirror(frames, positions):
    """The right hand: each left frame flipped; east and west swap views."""
    flipped = [[row[::-1] for row in rows] for _, rows in frames]
    return list(zip(positions, [flipped[0], flipped[1], flipped[3], flipped[2]]))


INHAND_RIGHT = mirror(INHAND_LEFT, [(10, 12), (21, 15), (14, 13), (6, 11)])


def inhand(side):
    frames = INHAND_LEFT if side == "left" else INHAND_RIGHT
    sheet = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
    for d, ((ox, oy), rows) in enumerate(frames):
        L = Layer(32, 32)
        for y, row in enumerate(rows):
            for x, key in enumerate(row):
                if key != ".":
                    L.set(ox + x, oy + y, INHAND_PAL[key])
        sheet.paste(L.image(), ((d % 2) * 32, (d // 2) * 32))
    return sheet


